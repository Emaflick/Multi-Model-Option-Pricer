"""Print every Phase 6 gate (ROADMAP, D-039..D-042): measured value, tolerance, PASS/FAIL.

Reads the CSVs written by scripts/run_benchmarks.py (run it first) and re-derives every gate from
the raw per-run table with the analysis functions of that script, so gates and report agree.
Reported (not gated): VR, work-normalised efficiency, Sobol' rates, Heston bias, SE honesty.
Usage: .venv/bin/python scripts/phase6_gates.py [--dir report/figures]
"""

from __future__ import annotations

import argparse
import importlib.util
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location(
    "run_benchmarks", ROOT / "scripts" / "run_benchmarks.py"
)
RB = importlib.util.module_from_spec(spec)
spec.loader.exec_module(RB)
RESULTS: list[tuple[str, str]] = []
SLOPE_BAND = (-0.6, -0.4)


def gate(name: str, value: str, tol: str, ok: bool) -> None:
    RESULTS.append((name, "PASS" if ok else "FAIL"))
    print(f"  {name:<52} {value:<40} tol {tol:<24} {RESULTS[-1][1]}", flush=True)


def manifest_gate(d: Path) -> None:
    print("\n== Figures and tables regenerated by scripts/run_benchmarks.py (manifest + sha256)")
    man = pd.read_csv(d / "benchmark_manifest.csv")
    listed = set(man.file)
    for f in RB.FIGURES + RB.TABLES:
        row = man[man.file == f]
        ok = (
            len(row) == 1
            and (d / f).exists()
            and RB.sha256(d / f) == row.sha256.iloc[0]
            and row.written_by.iloc[0] == "scripts/run_benchmarks.py"
            and row.config.iloc[0] == "full"
        )
        gate(
            f"regenerated: {f}",
            f"run {row.run_id.iloc[0] if len(row) else '-'}",
            "sha256 match",
            ok,
        )
    stray = sorted(p.name for p in d.glob("benchmark_*.png") if p.name not in listed)
    gate("no unlisted benchmark_*.png", f"{len(stray)} stray {stray}", "0", not stray)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", type=Path, default=RB.OUT)
    d = ap.parse_args(argv).dir
    refs = pd.read_csv(d / "benchmark_references.csv")
    runs = pd.read_csv(d / "benchmark_runs.csv")
    timing = pd.read_csv(d / "benchmark_timing.csv")
    bias = pd.read_csv(d / "benchmark_bias.csv")
    conv = RB.convergence(runs, refs)
    summ = RB.summary(runs, refs, conv, timing)
    Nmax = int(conv.N.max())
    cfg = f"N = 2^{int(np.log2(conv.N.min()))}..2^{int(np.log2(Nmax))}, R = {int(conv.R.min())}"
    print(f"Phase 6 gates ({cfg}; seeds and procedure: D-039, D-040)")

    print("\n== References: COS vs Lewis vs smallest MC SE (D-039)")
    h = refs[refs.set != "bsm"]
    gap = float(np.abs(h.cos_minus_lewis).max())
    se_min = float(conv[conv.set != "bsm"].se_r0.min())
    gate("max |COS - Lewis| <= 0.01 x min Heston SE", f"{gap:.2e} vs SE {se_min:.2e}",
         f"<= {0.01 * se_min:.2e}", gap <= 0.01 * se_min)  # fmt: skip
    fo = refs[(refs.set == "heston_fo") & (refs.strike == "ATM call")].ref.iloc[0]
    pub = RB.FO_PUBLISHED
    print(f"  (FO K = 100 COS {fo:.9f} vs published {pub:.9f}: {fo - pub:+.1e}; not gated)")

    print("\n== ROADMAP: plain-MC log-log slope in [-0.6, -0.4] (Heston: noise only, D-040)")
    for _, r in summ[summ.method == "plain"].iterrows():
        for col, lab in (("slope_se", "SE (r = 0)"), ("slope_err", RB.err_name(r.set))):
            v, sd = r[col], r[col + "_sd"]
            ok = SLOPE_BAND[0] <= v <= SLOPE_BAND[1]
            gate(f"{r.set} {r.strike}: {lab}", f"{v:+.4f} (OLS sd {sd:.4f})", "[-0.6, -0.4]", ok)

    print("\n== plain MC vs closed form / COS within 3 SE at each N (r = 0; 66 tests, FWER 16 %)")
    for (s, k), g in conv[conv.method == "plain"].groupby(["set", "strike"], sort=False):
        z = g.sort_values("N").z_r0.to_numpy()
        a = np.abs(z)
        gate(f"{s} {k}: max_N |z|", f"{a.max():.2f} (n > 3: {np.sum(a > 3)}/{z.size})",
             "<= 3 at every N", bool(np.all(a <= 3)))  # fmt: skip
        print(f"     z by N: {np.array2string(z, precision=2, max_line_width=120)}")

    print("\n== Estimators unbiased within 3 SE (pooled over R x N; Heston vs plain MC at same dt)")
    for _, r in summ.iterrows():
        if r.method == "plain" and r.set != "bsm":
            continue  # Heston plain vs COS is the bias study below
        tgt = "Black" if r.set == "bsm" else "plain MC"
        gate(f"{r.set} {r.strike}: {r.method}", f"z = {r.z_pooled:+.2f} vs {tgt}", "|z| <= 3",
             abs(r.z_pooled) <= 3)  # fmt: skip

    manifest_gate(d)

    print(f"\n== Reported: VR at equal N and work-normalised efficiency at N = {Nmax} (D-040)")
    cols = ["set", "strike", "method", f"VR_se_N{Nmax}", f"VR_err_N{Nmax}", f"time_s_N{Nmax}",
            f"eff_N{Nmax}", "slope_err", "slope_err_sd", "se_ratio"]  # fmt: skip
    with pd.option_context("display.width", 200):
        print(summ[cols].round(4).to_string(index=False))
    print("  (slope_err of sobol = empirical RQMC rate; times are serial medians on this machine)")
    print("\n== Reported: Heston QE-M bias vs COS (CV runs, D-040)")
    bcols = ["set", "strike", "n_steps", "dt", "n_paths", "bias", "se", "bias_over_se",
             "halving_diff", "halving_se"]  # fmt: skip
    with pd.option_context("display.width", 200):
        print(bias[bcols].to_string(index=False, float_format=lambda v: f"{v:.5g}"))
    print("  in implied-vol units (bias / Black vega at the COS implied vol):")
    for _, b in bias.iterrows():
        r = refs[(refs.set == b.set) & (refs.strike == b.strike)].iloc[0]
        sig = float(RB.implied_vol(r.ref, r.F, r.K, r["T"], r.DF, int(r.cp)))
        vega = float(RB.bsm.vega(r.F, r.K, r["T"], r.DF, sig, int(r.cp)))
        print(f"    {b.set} {b.strike} n_steps {b.n_steps:>3}: {1e4 * b.bias / vega:+.2f} "
              f"+- {1e4 * b.se / vega:.2f} vol bp (sigma_COS {sig:.4f})")  # fmt: skip
    hp = summ[(summ.method == "plain") & (summ.set != "bsm")]
    for _, r in hp.iterrows():
        print(f"  pooled plain MC - COS, {r.set} {r.strike}: {r.pooled - r.unbiased_target:+.4f} "
              f"({r.z_pooled:+.2f} SE)")  # fmt: skip

    n_fail = sum(v == "FAIL" for _, v in RESULTS)
    print(f"\n{len(RESULTS) - n_fail}/{len(RESULTS)} gates PASS, {n_fail} FAIL")
    return int(n_fail > 0)


if __name__ == "__main__":
    raise SystemExit(main())
